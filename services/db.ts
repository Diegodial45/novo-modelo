interface StoredLocalDB {
  menu: MenuItem[];
  categories: string[];
  tables: Table[];
  cashierHistory: CashierSession[];
  dailyRecords: DailyRecord[];
  expenses: Expense[];
  payables: Payable[];
  footerData: FooterData | null;
  employeesData: { employees: Employee[]; records: EmployeeRecord[] };
}

function getLocalData(): StoredLocalDB {
  try {
    if (typeof window !== 'undefined' && typeof localStorage !== 'undefined') {
      const raw = localStorage.getItem(LOCAL_STORAGE_DB_KEY);
      if (raw) {
        return JSON.parse(raw);
      }
    }
  } catch (e) {
    console.warn('Erro ao ler dados locais:', e);
  }

  return {
    menu: INITIAL_MENU,
    categories: INITIAL_CATEGORIES,
    tables: Array.from({ length: TOTAL_DEFAULT_TABLES }, (_, i) => ({ id: i + 1, isActive: false, items: [] })),
    cashierHistory: [],
    dailyRecords: [],
    expenses: [],
    payables: [],
    footerData: null,
    employeesData: { employees: [], records: [] }
  };
}

function saveLocalData(data: Partial<StoredLocalDB>) {
  try {
    if (typeof window !== 'undefined' && typeof localStorage !== 'undefined') {
      const current = getLocalData();
      const updated = { ...current, ...data };
      localStorage.setItem(LOCAL_STORAGE_DB_KEY, JSON.stringify(updated));
    }
  } catch (e) {
    console.warn('Erro ao salvar dados locais:', e);
  }
}

export const dbService = {
  // --- Inicialização e Carga ---
  async fetchAllData(): Promise<StoredLocalDB> {
    const local = getLocalData();

    try {
      // Test or fetch from Supabase with safety
      const [
        menuRes,
        catsRes,
        tablesRes,
        cashierRes,
        recordsRes,
        expRes,
        payablesRes,
        settingsRes,
        employeesDataRes
      ] = await Promise.all([
        supabase.from('menu_items').select('*'),
        supabase.from('categories').select('*'),
        supabase.from('tables').select('*').order('id'),
        supabase.from('cashier_sessions').select('*').order('opened_at', { ascending: false }),
        supabase.from('daily_records').select('*').order('closed_at', { ascending: false }),
        supabase.from('expenses').select('*').order('timestamp', { ascending: false }),
        supabase.from('payables').select('*').order('due_date', { ascending: true }),
        supabase.from('settings').select('*').eq('key', 'footer_data').maybeSingle(),
        supabase.from('settings').select('*').eq('key', 'employees_data').maybeSingle()
      ]);

      const hasSchemaError = [menuRes, catsRes, tablesRes].some(
        r => r.error && (r.error.code === 'PGRST205' || r.error.code === 'PGRST204' || r.error.message?.includes('schema cache'))
      );

      if (hasSchemaError) {
        console.warn('Tabelas Supabase ainda não foram criadas. Operando com cache local seguro.');
        return local;
      }

      // Se conectou com sucesso e tem tabelas:
      let categories = catsRes.data?.map((c: any) => c.name) || [];
      if (categories.length === 0 && local.categories.length > 0) {
        // Tentar semear categorias no Supabase
        await Promise.allSettled(local.categories.map(c => supabase.from('categories').insert({ name: c })));
        categories = local.categories;
      }

      let menu = menuRes.data || [];
      if (menu.length === 0 && local.menu.length > 0) {
        // Tentar semear cardápio no Supabase
        const menuToInsert = local.menu.map(m => ({
          id: m.id,
          name: m.name,
          description: m.description,
          price: m.price,
          cost_price: m.costPrice || 0,
          category: m.category,
          image_url: m.imageUrl,
          is_available: m.isAvailable,
          stock: m.stock
        }));
        await supabase.from('menu_items').insert(menuToInsert);
        menu = menuToInsert;
      }

      const mappedMenu: MenuItem[] = menu.map((m: any) => ({
        id: m.id,
        name: m.name,
        description: m.description,
        price: Number(m.price) || 0,
        costPrice: Number(m.cost_price) || 0,
        category: m.category,
        imageUrl: m.image_url || m.imageUrl,
        isAvailable: m.is_available ?? m.isAvailable ?? true,
        stock: Number(m.stock) || 0
      }));

      const mappedTables: Table[] = tablesRes.data && tablesRes.data.length > 0
        ? tablesRes.data.map((t: any) => ({
            id: t.id,
            isActive: Boolean(t.is_active),
            items: t.items || [],
            openedAt: t.opened_at,
            customerName: t.customer_name
          }))
        : local.tables;

      const mappedCashier: CashierSession[] = (cashierRes.data || []).map((c: any) => ({
        id: c.id,
        openedAt: Number(c.opened_at),
        closedAt: c.closed_at ? Number(c.closed_at) : undefined,
        openingBalance: Number(c.opening_balance),
        closingBalance: c.closing_balance ? Number(c.closing_balance) : undefined,
        expectedBalance: c.expected_balance ? Number(c.expected_balance) : undefined,
        status: c.status
      }));

      const mappedRecords: DailyRecord[] = (recordsRes.data || []).map((r: any) => ({
        id: r.id,
        tableId: r.table_id,
        customerName: r.customer_name,
        openedAt: Number(r.opened_at),
        closedAt: Number(r.closed_at),
        items: r.items || [],
        total: Number(r.total),
        paymentMethod: r.payment_method,
        sessionId: r.session_id
      }));

      const mappedExpenses: Expense[] = (expRes.data || []).map((e: any) => ({
        id: e.id,
        description: e.description,
        amount: Number(e.amount),
        category: e.category,
        timestamp: Number(e.timestamp),
        sessionId: e.session_id
      }));

      const mappedPayables: Payable[] = (payablesRes.data || []).map((p: any) => ({
        id: p.id,
        description: p.description,
        amount: Number(p.amount),
        dueDate: Number(p.due_date),
        status: p.status,
        paidAt: p.paid_at ? Number(p.paid_at) : undefined
      }));

      const finalData: StoredLocalDB = {
        menu: mappedMenu.length > 0 ? mappedMenu : local.menu,
        categories: categories.length > 0 ? categories : local.categories,
        tables: mappedTables,
        cashierHistory: mappedCashier.length > 0 ? mappedCashier : local.cashierHistory,
        dailyRecords: mappedRecords.length > 0 ? mappedRecords : local.dailyRecords,
        expenses: mappedExpenses.length > 0 ? mappedExpenses : local.expenses,
        payables: mappedPayables.length > 0 ? mappedPayables : local.payables,
        footerData: settingsRes.data?.value || local.footerData,
        employeesData: employeesDataRes.data?.value || local.employeesData
      };

      saveLocalData(finalData);
      return finalData;
    } catch (e) {
      console.warn('Conexão Supabase indisponível no momento. Usando dados locais.', e);
      return local;
    }
  },

  // --- Sincronizar todos os dados locais para o Supabase ---
  async syncLocalToSupabase(): Promise<{ success: boolean; message: string }> {
    const local = getLocalData();
    try {
      // 1. Categories
      if (local.categories.length > 0) {
        await Promise.allSettled(
          local.categories.map(c => supabase.from('categories').upsert({ name: c }, { onConflict: 'name' }))
        );
      }

      // 2. Menu
      if (local.menu.length > 0) {
        const menuToUpsert = local.menu.map(m => ({
          id: m.id,
          name: m.name,
          description: m.description,
          price: m.price,
          cost_price: m.costPrice || 0,
          category: m.category,
          image_url: m.imageUrl,
          is_available: m.isAvailable,
          stock: m.stock
        }));
        const { error } = await supabase.from('menu_items').upsert(menuToUpsert);
        if (error) throw error;
      }

      // 3. Mesas
      if (local.tables.length > 0) {
        const tablesToUpsert = local.tables.map(t => ({
          id: t.id,
          is_active: t.isActive,
          items: t.items,
          opened_at: t.openedAt,
          customer_name: t.customerName
        }));
        await supabase.from('tables').upsert(tablesToUpsert);
      }

      // 4. Sessões de Caixa
      if (local.cashierHistory.length > 0) {
        const sessions = local.cashierHistory.map(c => ({
          id: c.id,
          opened_at: c.openedAt,
          closed_at: c.closedAt,
          opening_balance: c.openingBalance,
          closing_balance: c.closingBalance,
          expected_balance: c.expectedBalance,
          status: c.status
        }));
        await supabase.from('cashier_sessions').upsert(sessions);
      }

      // 5. Vendas
      if (local.dailyRecords.length > 0) {
        const records = local.dailyRecords.map(r => ({
          id: r.id,
          table_id: r.tableId,
          customer_name: r.customerName,
          opened_at: r.openedAt,
          closed_at: r.closedAt,
          items: r.items,
          total: r.total,
          payment_method: r.paymentMethod,
          session_id: r.sessionId
        }));
        await supabase.from('daily_records').upsert(records);
      }

      // 6. Despesas
      if (local.expenses.length > 0) {
        const exps = local.expenses.map(e => ({
          id: e.id,
          description: e.description,
          amount: e.amount,
          category: e.category,
          timestamp: e.timestamp,
          session_id: e.sessionId
        }));
        await supabase.from('expenses').upsert(exps);
      }

      // 7. Contas
      if (local.payables.length > 0) {
        const pays = local.payables.map(p => ({
          id: p.id,
          description: p.description,
          amount: p.amount,
          due_date: p.dueDate,
          status: p.status,
          paid_at: p.paidAt
        }));
        await supabase.from('payables').upsert(pays);
      }

      // 8. Settings
      if (local.footerData) {
        await supabase.from('settings').upsert({ key: 'footer_data', value: local.footerData });
      }
      if (local.employeesData) {
        await supabase.from('settings').upsert({ key: 'employees_data', value: local.employeesData });
      }

      return { success: true, message: 'Todos os dados locais foram sincronizados com o Supabase com sucesso!' };
    } catch (err: any) {
      console.error('Falha na sincronização:', err);
      return {
        success: false,
        message: err.message || 'Erro ao sincronizar. Verifique se as tabelas foram criadas no Supabase.'
      };
    }
  },

  // --- Menu e Categorias ---
  async upsertMenuItem(item: MenuItem) {
    const local = getLocalData();
    const existingIdx = local.menu.findIndex(m => m.id === item.id);
    if (existingIdx >= 0) {
      local.menu[existingIdx] = item;
    } else {
      local.menu.push(item);
    }
    saveLocalData({ menu: local.menu });

    try {
      await supabase.from('menu_items').upsert({
        id: item.id,
        name: item.name,
        description: item.description,
        price: item.price,
        cost_price: item.costPrice || 0,
        category: item.category,
        image_url: item.imageUrl,
        is_available: item.isAvailable,
        stock: item.stock
      });
    } catch (e) {
      console.warn('Erro ao salvar item no Supabase:', e);
    }
  },

  async updateStock(id: string, newStock: number) {
    const local = getLocalData();
    const item = local.menu.find(m => m.id === id);
    if (item) {
      item.stock = newStock;
      saveLocalData({ menu: local.menu });
    }

    try {
      await supabase.from('menu_items').update({ stock: newStock }).eq('id', id);
    } catch (e) {
      console.warn('Erro ao atualizar estoque no Supabase:', e);
    }
  },

  async addCategory(name: string) {
    const local = getLocalData();
    if (!local.categories.includes(name)) {
      local.categories.push(name);
      saveLocalData({ categories: local.categories });
    }

    try {
      await supabase.from('categories').insert({ name });
    } catch (e) {
      console.warn('Erro ao adicionar categoria no Supabase:', e);
    }
  },

  async removeCategory(name: string) {
    const local = getLocalData();
    local.categories = local.categories.filter(c => c !== name);
    saveLocalData({ categories: local.categories });

    try {
      await supabase.from('categories').delete().eq('name', name);
    } catch (e) {
      console.warn('Erro ao remover categoria no Supabase:', e);
    }
  },

  // --- Caixa ---
  async createSession(session: CashierSession) {
    const local = getLocalData();
    const existing = local.cashierHistory.find(s => s.id === session.id);
    if (!existing) {
      local.cashierHistory.unshift(session);
      saveLocalData({ cashierHistory: local.cashierHistory });
    }

    try {
      await supabase.from('cashier_sessions').insert({
        id: session.id,
        opened_at: session.openedAt,
        opening_balance: session.openingBalance,
        status: session.status
      });
    } catch (e) {
      console.warn('Erro ao criar sessão de caixa no Supabase:', e);
    }
  },

  async closeSession(id: string, closedAt: number, closingBalance: number) {
    const local = getLocalData();
    const session = local.cashierHistory.find(s => s.id === id);
    if (session) {
      session.status = 'CLOSED';
      session.closedAt = closedAt;
      session.closingBalance = closingBalance;
      saveLocalData({ cashierHistory: local.cashierHistory });
    }

    try {
      await supabase.from('cashier_sessions').update({
        status: 'CLOSED',
        closed_at: closedAt,
        closing_balance: closingBalance
      }).eq('id', id);
    } catch (e) {
      console.warn('Erro ao fechar sessão no Supabase:', e);
    }
  },

  // --- Vendas e Despesas ---
  async addDailyRecord(record: DailyRecord) {
    const local = getLocalData();
    local.dailyRecords.unshift(record);
    saveLocalData({ dailyRecords: local.dailyRecords });

    try {
      await supabase.from('daily_records').insert({
        id: record.id,
        table_id: record.tableId,
        customer_name: record.customerName,
        opened_at: record.openedAt,
        closed_at: record.closedAt,
        items: record.items,
        total: record.total,
        payment_method: record.paymentMethod,
        session_id: record.sessionId
      });
    } catch (e) {
      console.warn('Erro ao gravar venda no Supabase:', e);
    }
  },

  async deleteDailyRecord(id: string) {
    const local = getLocalData();
    local.dailyRecords = local.dailyRecords.filter(r => r.id !== id);
    saveLocalData({ dailyRecords: local.dailyRecords });

    try {
      await supabase.from('daily_records').delete().eq('id', id);
    } catch (e) {
      console.warn('Erro ao excluir venda no Supabase:', e);
    }
  },

  async addExpense(expense: Expense) {
    const local = getLocalData();
    local.expenses.unshift(expense);
    saveLocalData({ expenses: local.expenses });

    try {
      await supabase.from('expenses').insert({
        id: expense.id,
        description: expense.description,
        amount: expense.amount,
        category: expense.category,
        timestamp: expense.timestamp,
        session_id: expense.sessionId
      });
    } catch (e) {
      console.warn('Erro ao adicionar despesa no Supabase:', e);
    }
  },

  async deleteExpense(id: string) {
    const local = getLocalData();
    local.expenses = local.expenses.filter(e => e.id !== id);
    saveLocalData({ expenses: local.expenses });

    try {
      await supabase.from('expenses').delete().eq('id', id);
    } catch (e) {
      console.warn('Erro ao excluir despesa no Supabase:', e);
    }
  },

  // --- Contas a Pagar ---
  async addPayable(payable: Payable) {
    const local = getLocalData();
    local.payables.unshift(payable);
    saveLocalData({ payables: local.payables });

    try {
      await supabase.from('payables').insert({
        id: payable.id,
        description: payable.description,
        amount: payable.amount,
        due_date: payable.dueDate,
        status: payable.status,
        paid_at: payable.paidAt
      });
    } catch (e) {
      console.warn('Erro ao adicionar conta no Supabase:', e);
    }
  },

  async markPayableAsPaid(id: string, paidAt: number) {
    const local = getLocalData();
    const item = local.payables.find(p => p.id === id);
    if (item) {
      item.status = 'PAID';
      item.paidAt = paidAt;
      saveLocalData({ payables: local.payables });
    }

    try {
      await supabase.from('payables').update({
        status: 'PAID',
        paid_at: paidAt
      }).eq('id', id);
    } catch (e) {
      console.warn('Erro ao marcar conta como paga no Supabase:', e);
    }
  },

  async deletePayable(id: string) {
    const local = getLocalData();
    local.payables = local.payables.filter(p => p.id !== id);
    saveLocalData({ payables: local.payables });

    try {
      await supabase.from('payables').delete().eq('id', id);
    } catch (e) {
      console.warn('Erro ao deletar conta no Supabase:', e);
    }
  },

  // --- Mesas (Tempo Real / Persistência) ---
  async updateTable(table: Table) {
    const local = getLocalData();
    const idx = local.tables.findIndex(t => t.id === table.id);
    if (idx >= 0) {
      local.tables[idx] = table;
    } else {
      local.tables.push(table);
    }
    saveLocalData({ tables: local.tables });

    try {
      await supabase.from('tables').upsert({
        id: table.id,
        is_active: table.isActive,
        items: table.items,
        opened_at: table.openedAt,
        customer_name: table.customerName
      });
    } catch (e) {
      console.warn('Erro ao sincronizar mesa no Supabase:', e);
    }
  },

  // --- Configurações ---
  async saveFooterData(data: FooterData) {
    saveLocalData({ footerData: data });
    try {
      await supabase.from('settings').upsert({
        key: 'footer_data',
        value: data
      });
    } catch (e) {
      console.warn('Erro ao salvar footerData no Supabase:', e);
    }
  },

  // --- Funcionários ---
  async saveEmployeesData(employeesData: { employees: Employee[]; records: EmployeeRecord[] }) {
    saveLocalData({ employeesData });
    try {
      await supabase.from('settings').upsert({
        key: 'employees_data',
        value: employeesData
      });
    } catch (e) {
      console.warn('Erro ao salvar funcionários no Supabase:', e);
    }
  }
};
